-- ============================================================================
-- ARS Computers — Make email optional in customer enquiry creation
-- Migration: 20261123000027_make_enquiry_email_optional.sql
-- ============================================================================
-- CONTEXT:
--   Customers and walk-in shop clients often provide only a 10-digit mobile
--   number without an email address. Previously, migration 20261107000003 made
--   the email segment strictly mandatory in `create_customer_enquiry`.
--
-- BEHAVIOUR:
--   * Email address is now OPTIONAL.
--   * At least one valid contact channel (phone or email) must be provided.
--   * Formats accepted:
--       - "phone"                 (10 to 15 digits; normalized canonical phone)
--       - "email"                 (valid email format)
--       - "phone | email"         (both channels combined)
--       - "email | phone"         (both channels combined)
--   * If phone is provided: normalized to 10-15 digits.
--   * If email is provided: normalized to lowercase.
--   * If both phone and email are provided, stored canonically as "phone | email".
--   * If neither is provided, raises user-friendly exception.
--
-- SAFETY & GRANTS:
--   * Signature (TEXT, TEXT, TEXT, TEXT) and return type JSONB are identical.
--   * SECURITY DEFINER with search_path = '' preserved.
--   * REVOKE FROM PUBLIC; GRANT TO anon, authenticated preserved.
--   * No historical enquiry records or tracking sessions are altered.
-- ============================================================================

CREATE OR REPLACE FUNCTION public.create_customer_enquiry(
  p_name TEXT,
  p_contact_info TEXT,
  p_category_interest TEXT,
  p_message TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_id UUID;
  v_number TEXT;
  v_name TEXT;
  v_contact TEXT;
  v_category TEXT;
  v_message TEXT;
  v_email TEXT;
  v_phone TEXT;
  v_segment TEXT;
BEGIN
  v_name := left(trim(COALESCE(p_name, '')), 120);
  v_contact := left(trim(COALESCE(p_contact_info, '')), 200);
  v_category := left(trim(COALESCE(p_category_interest, '')), 80);
  v_message := left(trim(COALESCE(p_message, '')), 2000);

  IF char_length(v_name) < 2 THEN
    RAISE EXCEPTION 'Please enter a valid name.' USING ERRCODE = '22023';
  END IF;

  -- Parse optional "phone[ | email]" or "email[ | phone]" segments.
  -- At least one valid contact channel (phone or email) is required.
  FOREACH v_segment IN ARRAY string_to_array(COALESCE(v_contact, ''), '|') LOOP
    v_segment := btrim(v_segment);
    CONTINUE WHEN v_segment = '';

    IF v_email IS NULL
       AND v_segment ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' THEN
      v_email := lower(v_segment);
    ELSIF v_phone IS NULL
         AND v_segment ~ '^[0-9+()\-\. ]+$'
         AND char_length(regexp_replace(v_segment, '[^0-9]', '', 'g')) BETWEEN 10 AND 15 THEN
      v_phone := regexp_replace(v_segment, '[^0-9]', '', 'g');
    ELSE
      RAISE EXCEPTION
        'Please provide a valid 10-digit mobile number or email address.'
        USING ERRCODE = '22023';
    END IF;
  END LOOP;

  IF v_phone IS NULL AND v_email IS NULL THEN
    RAISE EXCEPTION
      'Please provide at least a mobile number or an email address.'
      USING ERRCODE = '22023';
  END IF;

  IF char_length(v_message) < 5 THEN
    RAISE EXCEPTION 'Please provide brief details of your requirement.' USING ERRCODE = '22023';
  END IF;

  -- Insert with normal status/defaults. enquiry_number is generated by the
  -- existing database default/sequence.
  INSERT INTO public.enquiries (
    name,
    contact_info,
    category_interest,
    message,
    status
  ) VALUES (
    v_name,
    CASE
      WHEN v_phone IS NOT NULL AND v_email IS NOT NULL THEN v_phone || ' | ' || v_email
      WHEN v_phone IS NOT NULL THEN v_phone
      ELSE v_email
    END,
    NULLIF(v_category, ''),
    v_message,
    'new'
  )
  RETURNING id, enquiry_number INTO v_id, v_number;

  RETURN jsonb_build_object(
    'id', v_id,
    'enquiry_number', v_number
  );
END;
$$;

REVOKE EXECUTE ON FUNCTION public.create_customer_enquiry(TEXT, TEXT, TEXT, TEXT) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.create_customer_enquiry(TEXT, TEXT, TEXT, TEXT) FROM authenticated;
GRANT EXECUTE ON FUNCTION public.create_customer_enquiry(TEXT, TEXT, TEXT, TEXT) TO anon, authenticated;
