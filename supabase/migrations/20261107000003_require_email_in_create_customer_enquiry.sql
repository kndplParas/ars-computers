-- ============================================================================
-- ARS Computers — Require a valid email in customer enquiry submissions
-- Migration: 20261107000003_require_email_in_create_customer_enquiry.sql
-- ============================================================================
-- CONTEXT:
--   Customer-facing enquiry forms now make the email address required (the OTP
--   tracking system delivers verification codes to the enquiry's email). This
--   migration adds matching backend validation inside the public
--   `create_customer_enquiry` RPC so submissions cannot bypass the frontend.
--
-- BEHAVIOUR:
--   * Accepts the existing formats the two customer forms send:
--       - "email"                        (email only)
--       - "phone | email"                (combined segment format; the tracking
--                                         helper matches mobile via the digits
--                                         segment and email via the email segment)
--     The phone segment is optional; the email segment is MANDATORY.
--   * Concrete rejection reasons are returned as customer-readable messages
--     (they surface verbatim in both forms' error banners).
--   * Stores contact_info canonically as "phone_digits | email" when a phone
--     was provided, or the trimmed email alone otherwise, which keeps
--     `tracking_enquiry_ids_for_identifier` matching reliable for both channels.
--
-- SAFETY:
--   * Function signature (TEXT, TEXT, TEXT, TEXT), RETURNS JSONB, LANGUAGE
--     plpgsql, SECURITY DEFINER, empty search_path, and grants are unchanged
--     from the applied migration 20261106000003 (lines 135-199): anon and
--     authenticated keep EXECUTE; PUBLIC and authenticated do not gain anything.
--   * No historical enquiries, OTP rows, sessions, staff records or permissions
--     are modified. New submissions only are validated by this new body.
--   * Stricter validation is intentional: server-side phone-only submissions
--     are now rejected with an explicit "email is required" message, matching
--     the new policy on both customer forms.
-- ============================================================================

CREATE OR REPLACE FUNCTION public.create_customer_enquiry(
  p_name TEXT,
  p_contact_info TEXT,
  p_category_interest TEXT,
  p_message TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_id UUID;
  v_number TEXT;
  v_name TEXT;
  v_contact TEXT;
  v_category TEXT;
  v_message TEXT;
  v_email TEXT;
  v_phone TEXT;
  v_segment TEXT;
BEGIN
  v_name := left(trim(COALESCE(p_name, '')), 120);
  v_contact := left(trim(COALESCE(p_contact_info, '')), 200);
  v_category := left(trim(COALESCE(p_category_interest, '')), 80);
  v_message := left(trim(COALESCE(p_message, '')), 2000);

  IF char_length(v_name) < 2 THEN
    RAISE EXCEPTION 'Please enter a valid name.' USING ERRCODE = '22023';
  END IF;

  -- Parse optional "phone[ | email]" or "email[ | phone]" segments. Exactly one
  -- email segment is required; at most one optional phone segment is allowed.
  FOREACH v_segment IN ARRAY string_to_array(COALESCE(v_contact, ''), '|') LOOP
    v_segment := btrim(v_segment);
    CONTINUE WHEN v_segment = '';

    IF v_email IS NULL
       AND v_segment ~ '^[^[:space:]@]+@[^[:space:]@]+\.[^[:space:]@]+$' THEN
      v_email := v_segment;
    ELSIF v_phone IS NULL
         AND v_segment ~ '^[0-9+()\-\. ]+$'
         AND char_length(regexp_replace(v_segment, '[^0-9]', '', 'g')) BETWEEN 10 AND 15 THEN
      v_phone := regexp_replace(v_segment, '[^0-9]', '', 'g');
    ELSE
      RAISE EXCEPTION
        'Please provide a valid email address (e.g. name@example.com), optionally followed by your mobile number (e.g. name@example.com | 98XXXXXXXX).'
        USING ERRCODE = '22023';
    END IF;
  END LOOP;

  IF v_email IS NULL THEN
    RAISE EXCEPTION
      'Email address is required. Your verification code and enquiry tracking updates are sent to this email address.'
      USING ERRCODE = '22023';
  END IF;

  IF char_length(v_message) < 5 THEN
    RAISE EXCEPTION 'Please provide brief details of your requirement.' USING ERRCODE = '22023';
  END IF;

  -- Insert with normal status/defaults. enquiry_number is generated by the
  -- existing database default/sequence.
  INSERT INTO public.enquiries (
    name,
    contact_info,
    category_interest,
    message,
    status
  ) VALUES (
    v_name,
    CASE
      WHEN v_phone IS NOT NULL THEN v_phone || ' | ' || v_email
      ELSE v_email
    END,
    NULLIF(v_category, ''),
    v_message,
    'new'
  )
  RETURNING id, enquiry_number INTO v_id, v_number;

  RETURN jsonb_build_object(
    'id', v_id,
    'enquiry_number', v_number
  );
END;
$$;

REVOKE EXECUTE ON FUNCTION public.create_customer_enquiry(TEXT, TEXT, TEXT, TEXT) FROM PUBLIC;
REVOKE EXECUTE ON FUNCTION public.create_customer_enquiry(TEXT, TEXT, TEXT, TEXT) FROM authenticated;
GRANT EXECUTE ON FUNCTION public.create_customer_enquiry(TEXT, TEXT, TEXT, TEXT) TO anon, authenticated;
